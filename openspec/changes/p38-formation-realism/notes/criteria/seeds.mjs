// P38 判据评测用的**冻结种子集**（10 个 = `BENCHMARK_SEEDS` 5 个 + 5 个扩容）。
//
// 为什么不用 `BENCHMARK_SEEDS`（5 个）或它前 3 个：
//   判据组里现在有**射门**——一个计数统计量。基线 5 种子上普通射门 **5–9/场**，
//   单点 sem≈0.7；3 种子时 sem≈0.9，而判据要区分的差异量级只有 1–2 球/场
//   （exp8 单独：7.9→9.6）。**种子数不够时射门判据就是噪声判据**。
//   10 种子 sem≈0.5（口径论证见 notes/lag-sweep.md §1）。
//
// 冻结（不许按结果重挑）——与引擎 L1 门的「种子集冻结」是同一条教训。
// 需要快速迭代时可 `CRITERIA_SEEDS=42,1,7` 临时覆盖，但**入库的阈值必须用全量重标**。
export const CRITERIA_SEEDS = (process.env.CRITERIA_SEEDS
  ? process.env.CRITERIA_SEEDS.split(',').map(Number)
  : [42, 1, 7, 99, 123, 2, 3, 5, 11, 17]);

// 判据里的「每场」= 每 **90 分钟（5400s）**——引擎一场就是 5400s，
// 而 Metrica 两场的帧跨度是 5800s / 5646s。射门是**速率**量，不归一化就是拿
// 96.7 分钟的比赛去比 90 分钟的：口径分叉，正是 P36/P38 反复出的那类错。
export const PER_MATCH_SEC = 5400;
